"""CLI imports GPU/environment libraries only for commands that need them."""
import argparse
import importlib
from .common import ROOT


def main():
    p = argparse.ArgumentParser(description="WebShop team experiment tools (run from repository root)")
    sub = p.add_subparsers(dest="command", required=True)
    s = sub.add_parser("import-assets", help="Safely unpack local data.zip/indexes.zip and import SFT JSON")
    s.add_argument("--source", required=True)
    s = sub.add_parser("audit", help="Audit original splits and sample trajectories; no GPU required")
    s.add_argument("--sft", default=str(ROOT / "data/raw/webshop_sft.json"))
    s.add_argument("--output", default="artifacts/audit.json")
    s = sub.add_parser("split", help="Create deterministic task/instruction-disjoint train/val partitions")
    s.add_argument("--sft", default="data/raw/webshop_sft.json")
    s.add_argument("--test-ids", default=str(ROOT / "upstream/eval_agent/data/webshop/test_indices.json"))
    s.add_argument("--output", default="data/processed")
    s.add_argument("--val-fraction", type=float, default=.1)
    s.add_argument("--seed", type=int, default=42)
    s.add_argument("--goal-map", help="Environment-exported goal instructions, required before final training/evaluation")
    s = sub.add_parser("doctor", help="Report versions, GPU and local asset availability")
    s.add_argument("--output", default="artifacts/doctor.json")
    s = sub.add_parser("sft", help="Assistant-only LoRA SFT with optional 4-bit base")
    s.add_argument("--config", required=True)
    s.add_argument("--max-steps", type=int, default=-1)
    s = sub.add_parser("env-server", help="Local single-client WebShop environment HTTP bridge")
    s.add_argument("--port", type=int, default=8765)
    s = sub.add_parser("rollout", help="Collect real episodes against the environment bridge")
    s.add_argument("--config", required=True)
    s.add_argument("--ids", required=True)
    s.add_argument("--output", required=True)
    s.add_argument("--limit", type=int, default=0)
    s.add_argument("--repeats", type=int, default=1)
    s = sub.add_parser("summarize", help="Summarize episode metrics with confidence interval")
    s.add_argument("--input", required=True)
    s.add_argument("--output", required=True)
    s = sub.add_parser("check-run", help="Audit JSONL completion against metadata selected_ids")
    s.add_argument("--meta", required=True)
    s.add_argument("--jsonl", required=True)
    s.add_argument("--config", help="Optional config file to re-hash against the metadata")
    s.add_argument("--output")
    s = sub.add_parser("evaluate", help="Completeness audit, purchase/success split, failure triage, figures")
    s.add_argument("--meta", required=True)
    s.add_argument("--jsonl", required=True)
    s.add_argument("--config")
    s.add_argument("--output", required=True)
    s.add_argument("--cases", help="Write a markdown failure-case sheet to this path")
    s.add_argument("--figures-dir", help="Write SVG figures into this directory")
    s.add_argument("--allow-partial", action="store_true", help="Summarize an interrupted run and label it partial")
    s.add_argument("--cases-per-class", type=int, default=1)
    s.add_argument("--method", choices=["B0", "B1", "P0", "R-TG", "R-PG", "R0", "R1"])
    s.add_argument("--split-ids", help="Frozen task ID list used by the run; required with --register-row")
    s.add_argument("--register-row", help="Write one results/experiment-register.csv row for this run")
    s.add_argument("--peak-vram-gb", type=float)
    s = sub.add_parser("check-parity", help="Verify that two arms differ only by the adapter")
    s.add_argument("--a-meta")
    s.add_argument("--b-meta")
    s.add_argument("--a-config")
    s.add_argument("--b-config")
    s.add_argument("--require-frozen", action="store_true", help="Treat an empty goal_fingerprint as an error")
    s.add_argument("--output")
    s = sub.add_parser("check-register", help="Validate results/experiment-register.csv against its evidence")
    s.add_argument("--register", default=str(ROOT / "results/experiment-register.csv"))
    s.add_argument("--root", default=str(ROOT))
    s.add_argument("--output")
    s.add_argument("--no-git-check", action="store_true", help="Skip git commit existence checks")
    s = sub.add_parser("figures", help="Draw the method comparison chart from the register")
    s.add_argument("--register", default=str(ROOT / "results/experiment-register.csv"))
    s.add_argument("--output", required=True)
    s = sub.add_parser("preflight", help="Check configs, IDs, parity and register before a GPU run")
    s.add_argument("--a-config")
    s.add_argument("--b-config")
    s.add_argument("--ids", help="Frozen task ID list for this split")
    s.add_argument("--register", default=None)
    s.add_argument("--root", default=str(ROOT))
    s.add_argument("--require-frozen", action="store_true")
    s.add_argument("--no-git-check", action="store_true")
    s.add_argument("--output")
    s = sub.add_parser("compare", help="Paired comparison of two runs on the same tasks")
    s.add_argument("--a-meta")
    s.add_argument("--a-jsonl", required=True)
    s.add_argument("--b-meta")
    s.add_argument("--b-jsonl", required=True)
    s.add_argument("--a-label", default="a")
    s.add_argument("--b-label", default="b")
    s.add_argument("--output")
    s = sub.add_parser("results-table", help="Render the register as a Markdown results table")
    s.add_argument("--register", default=str(ROOT / "results/experiment-register.csv"))
    s.add_argument("--output", required=True)
    s = sub.add_parser("reward-export", help="Convert annotated episodes to step-reward training records")
    s.add_argument("--input", required=True)
    s.add_argument("--output", required=True)
    s.add_argument("--mode", choices=["terminal", "uniform", "spa"], required=True)
    s.add_argument("--alpha", type=float, default=1.)
    s.add_argument("--beta", type=float, default=.5)
    s = sub.add_parser("progress-train", help="Train low-cost additive linear baseline, not neural SPA")
    s.add_argument("--train", required=True)
    s.add_argument("--val", required=True)
    s.add_argument("--output", required=True)
    s.add_argument("--dimensions", type=int, default=4096)
    s.add_argument("--epochs", type=int, default=100)
    s.add_argument("--seed", type=int, default=42)
    s = sub.add_parser("progress-predict", help="Annotate episodes using the low-cost linear estimator")
    s.add_argument("--model", required=True)
    s.add_argument("--input", required=True)
    s.add_argument("--output", required=True)
    args = p.parse_args()
    mapping = {
        "import-assets": ("data", "import_assets"), "audit": ("data", "audit"), "split": ("data", "split"),
        "doctor": ("doctor", "run"), "sft": ("sft", "run"), "env-server": ("environment", "serve"),
        "rollout": ("rollout", "run"), "summarize": ("metrics", "run"), "reward-export": ("rewards", "run"),
        "progress-train": ("progress", "train"), "progress-predict": ("progress", "predict"),
        "check-run": ("evaluation", "check_run"), "evaluate": ("evaluation", "evaluate"),
        "check-parity": ("evaluation", "parity"), "check-register": ("register", "run"),
        "figures": ("figures", "run"), "preflight": ("preflight", "run"),
        "compare": ("comparison", "run"), "results-table": ("register", "table")}
    module, func = mapping[args.command]
    getattr(importlib.import_module(f"webshop_lab.{module}"), func)(args)


if __name__ == "__main__":
    main()
